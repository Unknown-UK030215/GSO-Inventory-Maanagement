-- Create the app profile as part of Auth signup. Public signup can choose
-- only one of the three staff roles; admin roles must be assigned by a trusted
-- administrator in the Supabase SQL editor.
create or replace function public.handle_new_auth_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
    requested_role text;
    safe_role app_role;
begin
    requested_role := coalesce(new.raw_user_meta_data ->> 'role', 'staff');
    if requested_role not in ('staff', 'fuel-vehicle', 'warehouse') then
        requested_role := 'staff';
    end if;
    safe_role := requested_role::app_role;

    insert into public.account_profiles (
        id, username, email, display_name, role
    ) values (
        new.id,
        lower(btrim(coalesce(new.raw_user_meta_data ->> 'username', split_part(new.email, '@', 1)))),
        lower(new.email),
        btrim(coalesce(new.raw_user_meta_data ->> 'display_name', split_part(new.email, '@', 1))),
        safe_role
    );
    return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
    after insert on auth.users
    for each row execute function public.handle_new_auth_user();

-- Keep the profile's contact email in step with the verified Auth email.
create or replace function public.handle_auth_email_update()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
    if new.email is distinct from old.email then
        update public.account_profiles
        set email = lower(new.email), updated_at = now()
        where id = new.id;
    end if;
    return new;
end;
$$;

drop trigger if exists on_auth_email_updated on auth.users;
create trigger on_auth_email_updated
    after update of email on auth.users
    for each row execute function public.handle_auth_email_update();

create or replace function public.prevent_profile_role_escalation()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
    if auth.uid() is not null
       and (new.role is distinct from old.role or new.is_active is distinct from old.is_active)
       and public.current_role() <> 'super-admin' then
        raise exception 'Only a super administrator can change account roles or active status.';
    end if;
    new.updated_at := now();
    return new;
end;
$$;

