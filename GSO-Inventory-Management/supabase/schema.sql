-- To provision an additional administrator, first create/confirm the account
-- in Supabase Authentication → Users, then assign its role from SQL Editor:
--
--   update public.account_profiles
--   set role = 'super-admin'
--   where email = 'admin@your-domain.gov.ph';
--
-- Never add administrator self-registration to the public client.

-- ============================================================================
-- 20. PROVIDED ADMINISTRATOR ACCOUNTS  (seeded defaults)
-- ----------------------------------------------------------------------------
-- Ships two ready-to-use administrator logins so a fresh project is reachable
-- without any manual provisioning. They match src/data/adminAccounts.js.
--
--   Role           Username      Sign-in email                 Password
--   -------------  ------------  ----------------------------  ---------------
--   admin          admin         admin@gso.gov.ph              ChangeMe!2024
--   super-admin    superadmin    superadmin@gso.gov.ph         ChangeMe!2024
--
-- Sign in with the EMAIL at the hidden /admin-login route once Supabase is
-- configured. The accounts are created already email-confirmed with the
-- default `pgcrypto` (bcrypt) hash, and their roles are set to the two
-- administrator roles by this block.
--
-- ⚠ SECURITY
--   • Change BOTH passwords immediately after the first sign-in
--     (Profile Settings → Change Password), or edit the literal below to a
--     strong password and re-run this file before anyone signs in.
--   • Delete this whole block before a production deployment.
--   • Re-running this file is safe: an existing email is left untouched.
-- ============================================================================
do $$
declare
    seed_email        text;
    seed_username     text;
    seed_display_name text;
    seed_role         app_role;
    new_id            uuid;
    has_provider_id   boolean;
    seed_accounts     text[][] := array[
        ['admin@gso.gov.ph',      'admin',      'System Administrator', 'admin'],
        ['superadmin@gso.gov.ph', 'superadmin', 'Super Administrator',  'super-admin']
    ];
    i integer;
begin
    -- Logins created before the provider_id column was added key identities on
    -- a text id; newer projects use provider_id. Detect which shape is present.
    select exists (
        select 1 from information_schema.columns
        where table_schema = 'auth' and table_name = 'identities'
          and column_name = 'provider_id'
    ) into has_provider_id;

    for i in 1 .. array_length(seed_accounts, 1) loop
        seed_email        := seed_accounts[i][1];
        seed_username     := seed_accounts[i][2];
        seed_display_name := seed_accounts[i][3];
        seed_role         := seed_accounts[i][4]::app_role;

        -- Idempotent: skip an account whose email is already taken.
        select u.id into new_id from auth.users u where lower(u.email) = seed_email;
        if new_id is not null then
            continue;
        end if;

        new_id := gen_random_uuid();

        insert into auth.users (
            instance_id, id, aud, role, email, encrypted_password,
            email_confirmed_at, raw_app_meta_data, raw_user_meta_data,
            created_at, updated_at
        ) values (
            '00000000-0000-0000-0000-000000000000',
            new_id,
            'authenticated',
            'authenticated',
            seed_email,
            crypt('ChangeMe!2024', gen_salt('bf')),
            now(),
            '{"provider":"email","providers":["email"]}'::jsonb,
            jsonb_build_object(
                'username', seed_username,
                'display_name', seed_display_name,
                'role', 'staff'   -- the signup trigger clamps public roles
            ),
            now(),
            now()
        );

        if has_provider_id then
            insert into auth.identities (
                id, user_id, provider_id, identity_data, provider,
                last_sign_in_at, created_at, updated_at
            ) values (
                gen_random_uuid(), new_id, new_id::text,
                jsonb_build_object('sub', new_id::text, 'email', seed_email, 'email_verified', true),
                'email', now(), now(), now()
            );
        else
            insert into auth.identities (
                id, user_id, identity_data, provider,
                last_sign_in_at, created_at, updated_at
            ) values (
                new_id::text, new_id,
                jsonb_build_object('sub', new_id::text, 'email', seed_email, 'email_verified', true),
                'email', now(), now(), now()
            );
        end if;

        -- on_auth_user_created already inserted the profile as 'staff'; promote
        -- it to its administrator role. auth.uid() is null in the SQL editor, so
        -- the role-escalation guard does not block this.
        update public.account_profiles
        set role         = seed_role,
            display_name = seed_display_name,
            is_active    = true,
            updated_at   = now()
        where id = new_id;
    end loop;
end $$;
