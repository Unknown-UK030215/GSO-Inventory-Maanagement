-- The JWT identity determines role and username. These SECURITY DEFINER
-- readers avoid recursive RLS checks and only ever return the caller's own
-- profile values.
create or replace function public.current_username()
returns text
language sql
stable
security definer
set search_path = public
as $$
    select coalesce((
        select p.username from public.account_profiles p where p.id = auth.uid()
    ), '');
$$;

