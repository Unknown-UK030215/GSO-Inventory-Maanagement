-- Who filed which form — the admin "find a form by who files it" shortcut.
create or replace view public.form_filing_summary as
    select
        form_type,
        register,
        registered_by,
        registered_by_name,
        count(*)          as records_filed,
        max(created_at)   as last_filed_at
    from public.assets
    group by form_type, register, registered_by, registered_by_name
    order by form_type, records_filed desc;

