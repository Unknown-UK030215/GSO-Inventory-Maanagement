-- ============================================================================
-- GSO INVENTORY MANAGEMENT — SUPABASE SCHEMA
-- General Services Office · Municipality of El Nido, Palawan
-- ----------------------------------------------------------------------------
-- This file converts every local GSO store (the browser `gso-*` keys) into a
-- relational Supabase/Postgres schema, so the same data the app keeps in
-- localStorage can be persisted server-side.
--
-- HOW TO USE
--   1. Supabase dashboard → SQL Editor → New query.
--   2. Paste this whole file and Run. It is idempotent (safe to re-run).
--   3. Point the app's contexts at these tables (see supabase/README notes at
--      the bottom of this file for the localStorage-key → table map).
--
-- SECURITY MODEL
--   • Passwords are owned by Supabase Auth; the app never stores credentials
--     in its own tables or browser localStorage when Supabase is configured.
--   • Public registration is limited to staff roles. Admin roles are assigned
--     only to an already-created Auth account from a trusted SQL editor.
--   • RLS uses the authenticated user's account_profiles role and username.
--     A service_role/secret key must never be shipped to the browser.
-- ============================================================================

create extension if not exists pgcrypto;

-- ============================================================================
-- 0. SHARED TYPES & HELPERS
-- ============================================================================

-- The three staff roles plus the two administrator roles used by the app.
do $$
begin
    if not exists (select 1 from pg_type where typname = 'app_role') then
        create type app_role as enum ('staff', 'fuel-vehicle', 'warehouse', 'admin', 'super-admin');
    end if;
    if not exists (select 1 from pg_type where typname = 'asset_register') then
        create type asset_register as enum ('inventory', 'warehouse');
    end if;
end $$;

-- Usernames are matched case-insensitively throughout the app, so they are
-- stored lower-cased in one canonical column. This helper normalises input.
create or replace function public.normalize_username(value text)
returns text
language sql
immutable
as $$
    select lower(btrim(coalesce(value, '')));
$$;

-- ----------------------------------------------------------------------------
-- JWT claim readers. Used by the RLS policies below.
-- Set these custom claims when you mint a Supabase Auth token:
--   { "app_username": "juan", "app_role": "warehouse" }
-- If you instead connect with the service_role key from a server, RLS is
-- bypassed and these functions are simply unused.
-- ----------------------------------------------------------------------------
create or replace function public.current_username()
returns text
language sql
stable
as $$
    select public.normalize_username(coalesce(auth.jwt() ->> 'app_username', ''));
$$;

create or replace function public.current_role()
returns text
language sql
stable
as $$
    select coalesce(auth.jwt() ->> 'app_role', 'staff');
$$;

create or replace function public.is_admin()
returns boolean
language sql
stable
as $$
    select public.current_role() in ('admin', 'super-admin');
$$;

create or replace function public.is_super_admin()
returns boolean
language sql
stable
as $$
    select public.current_role() = 'super-admin';
$$;

-- Keep an `updated_at` column current on every table that declares one.
create or replace function public.touch_updated_at()
returns trigger
language plpgsql
as $$
begin
    new.updated_at = now();
    return new;
end;
$$;

-- ============================================================================
-- 1. ACCOUNTS  (localStorage: gso-local-users)
-- ----------------------------------------------------------------------------
-- Registered staff accounts. Administrator accounts (admin / super-admin) are
-- provisioned the same way but flagged by their role. The secret seed
-- passwords in src/data/adminAccounts.js should be replaced by rows here.
-- ============================================================================
create table if not exists public.app_users (
    id                   bigint generated by default as identity primary key,
    username             text not null,                                  -- canonical, lower-cased
    display_name         text not null,
    role                 app_role not null default 'staff',
    -- Salted PBKDF2-SHA256 credential (see src/services/passwordService.js)
    password_salt        text not null,
    password_hash        text not null,
    password_algorithm   text not null default 'pbkdf2-sha256',
    password_iterations  integer not null default 120000,
    is_active            boolean not null default true,
    created_at           timestamptz not null default now(),
    constraint app_users_username_key unique (username)
);

comment on table public.app_users is
    'Registered accounts (mirrors the gso-local-users store). Passwords are salted PBKDF2 hashes only.';

create index if not exists app_users_role_idx on public.app_users (role);

-- ============================================================================
-- 2. PROFILES  (localStorage: gso-user-profiles)
-- ----------------------------------------------------------------------------
-- Contact details, the recovery question/answer hash, and the lockout state
-- used by the forgot-password flow. One row per username.
-- ============================================================================
create table if not exists public.user_profiles (
    username               text primary key,                              -- FK-style link to app_users.username
    display_name           text,
    email                  text,
    phone                  text,
    department             text,
    designation            text,
    -- Password recovery (forgot-password)
    security_question      text,
    security_answer_hash   text,                                          -- PBKDF2 hash of the normalised answer
    security_answer_salt   text,
    recovery_attempts      integer not null default 0,                    -- wrong answers since last success
    recovery_locked_until  timestamptz,                                  -- non-null while recovery is locked
    password_changed_at    timestamptz,
    updated_at             timestamptz not null default now(),
    constraint user_profiles_username_fkey
        foreign key (username) references public.app_users (username) on delete cascade
);

comment on table public.user_profiles is
    'Profile details + recovery question/answer hash (mirrors gso-user-profiles).';

drop trigger if exists user_profiles_touch on public.user_profiles;
create trigger user_profiles_touch
    before update on public.user_profiles
    for each row execute function public.touch_updated_at();

-- ============================================================================
-- 3. ASSETS  (localStorage: gso-assets  +  gso-warehouse-assets)
-- ----------------------------------------------------------------------------
-- Both registers share one table, separated by the `register` column, exactly
-- as the app keeps them in two stores. Shared/first-class columns are typed;
-- every form-specific field (PARE, ICS, AIR, RIS, High Value, …) is kept in
-- `extra_fields` jsonb so the dynamic form registry needs no migration.
-- ============================================================================
create table if not exists public.assets (
    id                bigint primary key,                                 -- client-generated id (see note)
    register          asset_register not null default 'inventory',
    form_type         text not null,                                      -- ASSET_FORMS id, e.g. 'pare', 'ris', 'high-value'
    property_no       text,                                               -- shared across most forms
    description       text,
    classification    text,
    category          text,
    quantity          numeric(14,2),
    unit              text,
    cost              numeric(16,2),
    department        text,
    accountable       text,
    location          text,
    condition         text,
    status            text,
    remarks           text,
    acquisition_date  date,
    -- Everything a specific form collects that is not a shared column above
    -- (e.g. brand, model, serial_no, ics_no, ris_no, article, supplier, …).
    extra_fields      jsonb not null default '{}'::jsonb,
    -- Authorship — matches registeredBy / registeredByName in the app.
    registered_by      text,
    registered_by_name text,
    created_at        timestamptz not null default now(),
    updated_at        timestamptz not null default now()
);

comment on table public.assets is
    'Inventory + warehouse asset/form records (mirrors gso-assets and gso-warehouse-assets).';
comment on column public.assets.extra_fields is
    'Form-specific fields as JSON, kept out of the typed columns so new forms need no migration.';

create index if not exists assets_register_idx    on public.assets (register);
create index if not exists assets_form_type_idx   on public.assets (form_type);
create index if not exists assets_property_no_idx on public.assets (property_no);
create index if not exists assets_registered_by_idx on public.assets (registered_by);
create index if not exists assets_extra_fields_idx on public.assets using gin (extra_fields);

drop trigger if exists assets_touch on public.assets;
create trigger assets_touch
    before update on public.assets
    for each row execute function public.touch_updated_at();

