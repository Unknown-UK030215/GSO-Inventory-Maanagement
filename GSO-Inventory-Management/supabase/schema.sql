-- 19. SUPABASE AUTH ACCOUNT PROFILES & DATA RLS
-- ----------------------------------------------------------------------------
-- Authentication credentials live only in Supabase Auth (auth.users).
-- account_profiles holds the app username, display name, role and contact
-- settings. Roles for public sign-ups are whitelisted in the server trigger;
-- users cannot assign themselves administrator access.
-- ============================================================================
create table if not exists public.account_profiles (
